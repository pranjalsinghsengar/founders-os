"""Responses API adapter and bounded, allowlisted MCP stdio connections."""
import asyncio
import hashlib
import json
import os
import socket
import urllib.error
import urllib.request
from contextlib import AsyncExitStack
from core import ToolFailure


class OpenAIResponses:
    def __init__(self, model, api_key_env="OPENAI_API_KEY", max_output_tokens=2000):
        self.key = os.environ.get(api_key_env)
        if not self.key:
            raise ValueError("Missing model API credential environment variable")
        if model.startswith('gpt-oss'):
            raise ToolFailure('unsupported_hosted_model')
        self.model = model
        self.max_output_tokens = max_output_tokens

    def complete(self, instructions, history, tools):
        return self._request(instructions, history, tools)

    def research(self, instructions, history, max_search_calls=4):
        if type(max_search_calls) is not int or not 1 <= max_search_calls <= 8:
            raise ValueError('Research search-call limit must be 1..8')
        return self._request(instructions, history, [{'type': 'web_search'}],
            tool_choice='required', max_tool_calls=max_search_calls,
            include=['web_search_call.action.sources'])

    def _request(self, instructions, history, tools, **options):
        body = json.dumps({"model": self.model, "instructions": instructions,
                           "input": history, "tools": tools, "store": False,
                           "max_output_tokens": self.max_output_tokens,
                           "parallel_tool_calls": False, **options}).encode()
        request = urllib.request.Request("https://api.openai.com/v1/responses", body,
            {"Authorization": "Bearer " + self.key, "Content-Type": "application/json"})
        # No automatic retries: ambiguous calls may already incur provider costs.
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                return json.load(response)
        except urllib.error.HTTPError as error:
            status = error.code
            detail = {}
            if status == 429:
                try:
                    payload = json.loads(error.read(16384))
                    if isinstance(payload, dict) and isinstance(payload.get('error'), dict):
                        detail = payload['error']
                except (ValueError, OSError):
                    pass
            error.close()
            code = 'api_' + str(status) if status in (400,401,403,404,429) else ('api_server' if status >= 500 else 'api_other')
            if status == 429:
                if detail.get('code') in ('insufficient_quota', 'credit_balance_exhausted',
                                         'project_spend_limit_exceeded', 'organization_spend_limit_exceeded',
                                         'organization_usage_limit_exceeded'):
                    code = 'api_quota'
                elif detail.get('code') in ('rate_limit_exceeded', 'slow_down') or detail.get('type') == 'rate_limit_error':
                    code = 'api_rate_limit'
                elif detail.get('type') == 'insufficient_quota':
                    code = 'api_quota'
            raise ToolFailure(code) from None
        except (TimeoutError, socket.timeout):
            raise ToolFailure('network_timeout') from None
        except urllib.error.URLError:
            raise ToolFailure('network_connection') from None
        except (json.JSONDecodeError, UnicodeDecodeError):
            raise ToolFailure('invalid_response') from None


class MCPConnections:
    def __init__(self, servers):
        self.servers = servers
        self.stack = AsyncExitStack()
        self.tools = {}

    async def __aenter__(self):
        from mcp import ClientSession, StdioServerParameters
        from mcp.client.stdio import stdio_client
        try:
            for server in self.servers:
                # Config is trusted local operator input, never generated by a model.
                env = {k: os.environ[k] for k in ("PATH", "SYSTEMROOT") if k in os.environ}
                for key in server.get("env_names", []):
                    if key not in os.environ:
                        raise ValueError("Missing MCP credential/config environment variable")
                    env[key] = os.environ[key]
                params = StdioServerParameters(command=server["command"], args=server.get("args", []), env=env)
                read, write = await self.stack.enter_async_context(stdio_client(params))
                session = await self.stack.enter_async_context(ClientSession(read, write))
                await asyncio.wait_for(session.initialize(), 30)
                cursor = None
                pages = 0
                seen = set()
                while True:
                    listed = await asyncio.wait_for(session.list_tools(cursor=cursor), 30)
                    for tool in listed.tools:
                        rule = server.get("allow_tools", {}).get(tool.name)
                        if rule is None:
                            continue
                        canonical = server["name"] + "/" + tool.name
                        alias = "mcp_" + hashlib.sha256(canonical.encode()).hexdigest()[:24]
                        if alias in self.tools:
                            raise ValueError("Duplicate MCP tool identity")
                        cost = rule.get("cost_units", 0)
                        if type(cost) is not int or cost < 0:
                            raise ValueError("Invalid configured tool cost")
                        self.tools[alias] = {"session": session, "name": tool.name,
                            "canonical": canonical, "cost": cost, "schema": tool.inputSchema,
                            "definition": {"type": "function", "name": alias,
                                "description": (tool.description or tool.name)[:1500],
                                "parameters": tool.inputSchema}}
                    cursor = listed.nextCursor
                    if not cursor:
                        break
                    pages += 1
                    if cursor in seen or pages > 100:
                        raise ValueError("Invalid MCP tool pagination")
                    seen.add(cursor)
            return self
        except BaseException:
            await self.stack.aclose()
            raise

    async def __aexit__(self, *args):
        await self.stack.aclose()

    async def call(self, alias, arguments):
        from jsonschema import validate, ValidationError
        t = self.tools[alias]
        try:
            validate(arguments, t["schema"])
        except ValidationError:
            raise ToolFailure('mcp_schema') from None
        result = await asyncio.wait_for(t["session"].call_tool(t["name"], arguments), 45)
        if result.isError:
            # Match only fixed workspace policy diagnostics; arbitrary MCP error
            # text can contain credentials and must never enter events/UI.
            messages = [getattr(block,'text','') for block in result.content]
            path_errors = ('Unsupported product file or path outside workspace',
                           'Hidden files and traversal are prohibited',
                           'Relative product file required','Workspace symlinks are prohibited')
            if t['canonical'].startswith('workspace/') and any(
                    message.endswith(reason) for message in messages for reason in path_errors):
                raise ToolFailure('workspace_path')
            raise ToolFailure('mcp_tool')
        return result.model_dump(mode="json", by_alias=True, exclude_none=True)
